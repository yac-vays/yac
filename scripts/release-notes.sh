#!/usr/bin/env bash
#
# Generates the release notes page of the docs repo from the git history.
#
#   release-notes.sh             print the page to stdout
#   release-notes.sh --publish   commit the page to the docs repo and push it
#                                (done by release.sh on every release)
#
# The page is always rebuilt completely from the tags: one section per stable
# release (vX.Y) with the commits since the previous one, and on top one
# section for the latest release candidate if it is ahead of the latest stable
# release. Listed are conventional commits of type feat, fix and perf, as well
# as any commit marked as breaking ("type!:" or a "BREAKING CHANGE:" footer).
#
# DOCS_REMOTE overrides the URL of the docs repo (default: the repo
# yac-vays.github.io next to this one on the same remote).
#
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

origin=$(git config "remote.$(git config "branch.$(git branch --show-current).remote" || echo origin).url")
origin=${origin%.git}
repo=${origin##*[/:]}                                   # vays
name=${repo^^}                                          # VAYS
page="$repo/releases.md"                                # path in the docs repo
docs=${DOCS_REMOTE:-${origin%"$repo"}yac-vays.github.io.git}
web=$(sed -E 's#^(git@|ssh://git@|https://)([^/:]+)[/:]#https://\2/#' <<<"$origin")

# section <title> <tag> <previous tag or empty>
section() {
  local title=$1 tag=$2 prev=$3 range log breaking out='' kind heading
  range=${prev:+$prev..}$tag
  log=$(git log --no-merges --format='%h%x09%s' "$range")
  breaking=$(git log --no-merges --format='%h' -E --grep='^BREAKING[ -]CHANGE:' "$range" | xargs)

  for kind in breaking feat fix perf; do
    case $kind in
      breaking) heading='Breaking changes' ;;
      feat) heading='Features' ;;
      fix) heading='Fixes' ;;
      perf) heading='Performance' ;;
    esac
    local items
    items=$(awk -F'\t' -v kind="$kind" -v breaking=" $breaking " -v web="$web" '
      # escape what kramdown or liquid would interpret, except inside `code spans`
      function escape(text,    parts, n, i, out) {
        n = split(text, parts, "`")
        for (i = 1; i <= n; i++) {
          if (i % 2) { gsub(/[\\*<|\[\]]/, "\\\\&", parts[i]); gsub(/[{]/, "\\&#123;", parts[i]) }
          out = out (i > 1 ? "`" : "") parts[i]
        }
        return out
      }
      match($2, /^[a-z]+(\([^)]*\))?!?: */) {
        prefix = substr($2, 1, RLENGTH); text = substr($2, RLENGTH + 1)
        type = prefix; sub(/[(!:].*/, "", type)
        scope = ""
        if (match(prefix, /\([^)]*\)/)) scope = "**" escape(substr(prefix, RSTART + 1, RLENGTH - 2)) ":** "
        is_breaking = (prefix ~ /!: *$/ || index(breaking, " " $1 " "))
        if (kind == "breaking" ? !is_breaking : (is_breaking || type != kind)) next
        printf "  - %s%s ([%s](%s/commit/%s))\n", scope, escape(text), $1, web, $1
      }' <<<"$log")
    [ -z "$items" ] || out+=$'\n'"### $heading"$'\n'"{: .no_toc }"$'\n\n'"$items"$'\n'
  done

  [ -n "$out" ] || return 0
  echo
  echo "## $title"
  echo
  echo "$(git log -1 --format=%cs "$tag")${prev:+ · [all changes since $prev]($web/compare/$prev...$tag)}"
  printf '%s' "$out"
}

generate() {
  local stable rc tags i
  stable=$(git tag -l 'v[0-9]*.[0-9]*' | grep -E '^v[0-9]+\.[0-9]+$' | sort -V || true)
  rc=$(git tag -l 'v[0-9]*.[0-9]*rc[0-9]*' | grep -E '^v[0-9]+\.[0-9]+rc[0-9]+$' | sort -V | tail -1 || true)
  mapfile -t tags <<<"$stable"
  [ -n "$stable" ] || tags=()

  cat <<EOF
---
title: Release Notes
parent: $name
nav_order: 99
---

# Release Notes
{: .no_toc }

The notable changes of every $name release, taken from the
[commit history]($web/commits). See
[Versioning](install.md#versioning--container-tags) for the matching
container tags.

  - TOC
{:toc}

<!-- generated by scripts/release.sh of the $repo repo, do not edit -->
EOF

  # release candidate ahead of the latest stable release
  local last=''
  [ ${#tags[@]} -eq 0 ] || last=${tags[-1]}
  if [ -n "$rc" ] && [ "$(printf '%s\n' "${rc%%rc*}" "${last:-v0.0}" | sort -V | tail -1)" != "${last:-v0.0}" ]; then
    section "$rc (testing)" "$rc" "$last"
  fi

  for ((i = ${#tags[@]} - 1; i >= 0; i--)); do
    section "${tags[i]}" "${tags[i]}" "$([ "$i" -eq 0 ] || echo "${tags[i-1]}")"
  done
}

# commit the regenerated page in a fresh clone of the docs repo and push it
publish() {
  local dir latest
  dir=$(mktemp -d); trap "rm -rf '$dir'" EXIT
  git clone --quiet --depth 1 "$docs" "$dir"
  generate > "$dir/$page"
  latest=$(sed -n 's/^## \(v[^ ]*\).*/\1/p' "$dir/$page" | head -1)
  git -C "$dir" add "$page"
  if git -C "$dir" diff --cached --quiet; then
    echo "release notes: no changes"
  else
    git -C "$dir" commit --quiet -m "docs: $name release notes${latest:+ ($latest)}"
    git -C "$dir" push --quiet origin HEAD
    echo "release notes: published $page"
  fi
}

case "${1:-}" in
  '') generate ;;
  --publish) publish ;;
  *) sed -n '3,7p' "$0"; exit 1 ;;
esac
